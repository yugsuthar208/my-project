/**
 * Fast deterministic string-hash to select non-repeating consistent photos
 */
function hashString(str) {
  if (!str) return 0;
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0; // Convert to 32bit integer
  }
  return Math.abs(hash);
}

/**
 * Resolves the most accurate, vibrant cover image for any Trip object.
 * Checks stops, title, destination keywords, origin, or falls back to
 * a deterministic non-repeating master photo from the 20+ item pools.
 */
export function getTripCoverImage(trip, index = 0) {
  if (!trip) return KASHMIR_IMAGES[0];

  // 1. Direct trip cover property
  if (trip.cover_image && typeof trip.cover_image === "string" && trip.cover_image.startsWith("http")) {
    return trip.cover_image;
  }
  if (trip.image_url && typeof trip.image_url === "string" && trip.image_url.startsWith("http")) {
    return trip.image_url;
  }

  // 2. Stop city image if available
  const firstStopImg = trip.stops?.[0]?.city?.image_url;
  if (firstStopImg && typeof firstStopImg === "string" && firstStopImg.startsWith("http")) {
    return firstStopImg;
  }

  // 3. Keyword matching on Title, Stops, Origin, Description
  const title = (trip.title || "").toLowerCase();
  const origin = (trip.origin_city || "").toLowerCase();
  const stopsStr = (trip.stops || []).map((s) => s.city?.name || "").join(" ").toLowerCase();
  const combined = `${title} ${origin} ${stopsStr}`;

  // Kashmir check (20+ pool)
  if (
    combined.includes("kashmir") ||
    combined.includes("srinagar") ||
    combined.includes("gulmarg") ||
    combined.includes("pahalgam") ||
    combined.includes("sonamarg") ||
    combined.includes("dal lake") ||
    combined.includes("paradise")
  ) {
    const idx = (hashString(trip.id || trip.title || "kashmir") + index) % KASHMIR_IMAGES.length;
    return KASHMIR_IMAGES[idx];
  }

  // Rajasthan / Jaipur check (20+ pool)
  if (
    combined.includes("jaipur") ||
    combined.includes("rajasthan") ||
    combined.includes("udaipur") ||
    combined.includes("jodhpur") ||
    combined.includes("jaisalmer") ||
    combined.includes("heritage") ||
    combined.includes("palace") ||
    combined.includes("fort")
  ) {
    const idx = (hashString(trip.id || trip.title || "rajasthan") + index) % RAJASTHAN_IMAGES.length;
    return RAJASTHAN_IMAGES[idx];
  }

  // Himalayas / Mountains check
  if (
    combined.includes("manali") ||
    combined.includes("ladakh") ||
    combined.includes("leh") ||
    combined.includes("himalaya") ||
    combined.includes("mountain") ||
    combined.includes("snow") ||
    combined.includes("trek") ||
    combined.includes("shimla") ||
    combined.includes("rishikesh")
  ) {
    const idx = (hashString(trip.id || trip.title || "himalayas") + index) % HIMALAYAS_IMAGES.length;
    return HIMALAYAS_IMAGES[idx];
  }

  // South / Coastal / Beach check
  if (
    combined.includes("munnar") ||
    combined.includes("kerala") ||
    combined.includes("alleppey") ||
    combined.includes("goa") ||
    combined.includes("beach") ||
    combined.includes("hampi") ||
    combined.includes("mumbai")
  ) {
    const idx = (hashString(trip.id || trip.title || "coastal") + index) % SOUTH_COASTAL_IMAGES.length;
    return SOUTH_COASTAL_IMAGES[idx];
  }

  // Europe / Global check
  if (
    combined.includes("europe") ||
    combined.includes("paris") ||
    combined.includes("rome") ||
    combined.includes("tokyo") ||
    combined.includes("japan") ||
    combined.includes("asia") ||
    combined.includes("canada") ||
    combined.includes("norway") ||
    combined.includes("bali") ||
    combined.includes("dubai")
  ) {
    const idx = (hashString(trip.id || trip.title || "global") + index) % GLOBAL_IMAGES.length;
    return GLOBAL_IMAGES[idx];
  }

  // 4. Default / Generic Trip: Use deterministic non-repeating hash over MASTER_TRAVEL_POOL
  const stableKey = `${trip.id || ""}_${trip.title || ""}_${trip.created_at || ""}_${index}`;
  const poolIdx = hashString(stableKey) % MASTER_TRAVEL_POOL.length;
  return MASTER_TRAVEL_POOL[poolIdx];
}

/**
 * Resolves the cover image for any City / Destination recommendation card
 */
export function getCityCoverImage(city, index = 0) {
  if (!city) return KASHMIR_IMAGES[0];

  if (city.image_url && typeof city.image_url === "string" && city.image_url.startsWith("http")) {
    return city.image_url;
  }

  const name = (city.name || "").toLowerCase();
  const country = (city.country || "").toLowerCase();
  const combined = `${name} ${country}`;

  if (combined.includes("kashmir") || combined.includes("srinagar") || combined.includes("gulmarg") || combined.includes("pahalgam")) {
    const idx = (hashString(city.id || city.name) + index) % KASHMIR_IMAGES.length;
    return KASHMIR_IMAGES[idx];
  }

  if (combined.includes("jaipur") || combined.includes("rajasthan") || combined.includes("udaipur") || combined.includes("jodhpur")) {
    const idx = (hashString(city.id || city.name) + index) % RAJASTHAN_IMAGES.length;
    return RAJASTHAN_IMAGES[idx];
  }

  if (combined.includes("norway") || combined.includes("norge") || combined.includes("oslo") || combined.includes("bergen")) {
    return "https://images.unsplash.com/photo-1506744038136-46273834b3fb?w=1200&auto=format&fit=crop&q=80";
  }

  if (combined.includes("france") || combined.includes("paris")) {
    return "https://images.unsplash.com/photo-1502602898657-3e91760cbb34?w=1200&auto=format&fit=crop&q=80";
  }

  if (combined.includes("canada") || combined.includes("toronto") || combined.includes("vancouver") || combined.includes("banff")) {
    return "https://images.unsplash.com/photo-1517090504586-fde19ea6066f?w=1200&auto=format&fit=crop&q=80";
  }

  if (combined.includes("india")) {
    const idx = (hashString(city.id || city.name) + index) % RAJASTHAN_IMAGES.length;
    return RAJASTHAN_IMAGES[idx];
  }

  const idx = hashString(city.id || city.name || "dest") % MASTER_TRAVEL_POOL.length;
  return MASTER_TRAVEL_POOL[idx];
}

/**
 * Graceful image onError handler to replace broken URLs with high-quality fallback
 */
export function handleImageError(event, fallbackUrl = KASHMIR_IMAGES[0]) {
  if (event?.currentTarget) {
    event.currentTarget.onerror = null; // prevent infinite loops
    event.currentTarget.src = fallbackUrl;
  }
}
